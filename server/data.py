# ==========================================================================
# 景点判定标准 —— 本项目的权威定义,改过滤规则前先读完这一段
# ==========================================================================
#
# 【定义】
#   景点 = 以「供人观赏、游览、体验」为主要功能的场所,
#          游客会专程安排 30 分钟以上前往。
#
# 【三条判定线,缺一不可】
#   1) 功能线 —— 主要功能是「给人看 / 给人玩」,而不是提供生活服务或用于生产办公。
#      博物馆(看展)、古街(逛)、寺庙(参观)是景点;
#      餐厅(吃饭)、酒店(住)、派出所(办事)、写字楼与产业园区(办公生产)不是。
#      这条对应国标 GB/T 18972-2017《旅游资源分类、调查与评价》里反复出现的限定语:
#      「可供观光游览」「具有观赏游览功能的房屋/景观建筑」。
#      → 产业园区即便挂着「文创」二字,主功能仍是招商与办公,不满足这条。
#        这就是「产业园区也是景点?」的答案:不算。
#
#   2) 专程线 —— 游客会把它单独写进行程,而不是路过顺带,也不是周边居民的日常设施。
#      社区公园 / 口袋公园 / 街心公园 / 党群法治主题公园服务的是附近居民日常,
#      不是游客目的地;景区内部的子设施(「XX博物馆办公区」「XX公园办公室」)
#      以及尚未开放(「XX博物馆(建设中)」)的也不是独立行程项。
#
#   3) 可停留线 —— 能待 30 分钟以上,不是一个点位或一个瞬间。
#      环岛名、出入口、收费站不满足。
#
# 大众还是小众?两条线都不按名气卡:5A 景区和一条没评级但本地人都在逛的老街,
# 只要满足上面三条就是景点。名气只影响排序与是否进经典推荐,不影响"是不是景点"。
#
# 【执行顺序:白名单制】
#   第 0 关  名称     未开放 / 内部设施 / 社区级日常设施 / 写字楼楼栋 → 否
#   第 1 关  顶层大类 tags[0]:高德 23 个一级类里只有 4 个能出景点,其余一律 → 否
#   第 2 关  细分 type:在允许的大类里再剔除服务性、内部性的细分项
#   默认     → 否
#
#   旧版是黑名单制(「都不命中就保留」),产业园区正是从默认分支漏进来的。
#   改成白名单后,陌生类型宁可丢也不放 —— 丢一条只是少个备选,
#   放一条进来就是行程里出现「网易文创科技园」。
#
# 【为什么顶层大类这么可靠 —— 53 城 3880 条真实缓存的实测依据】
#   高德自己就把"文创园"分成了两类:
#     真对游客开放的:上海 M50 创意园 → type=旅游景点 / top=风景名胜
#                    重庆 TESTBED2 贰厂 → top=体育休闲服务
#                    上海云间粮仓文创园 → top=科教文化服务
#     纯办公楼群的:  网易上海国际文创科技园、大盛魁文创园A1区、百沐千文创园C栋
#                    → 一律 top=商务住宅
#   所以砍掉整个「商务住宅」大类不会误杀任何一个网红文创园,
#   却能干净地清掉 293 条(占全部 3880 条的 7.5%)办公楼。
#

